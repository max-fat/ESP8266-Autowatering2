/*
 * text.h - работа с пользовательскими строками (имена модуля и каналов).
 *
 * Имена приходят из веб-формы: их надо обрезать по длине поля, убрать лишние
 * пробелы и, главное, не разрезать посередине многобайтовый символ UTF-8 —
 * иначе в интерфейсе и в JSON окажется битая кириллица.
 *
 * Модуль без зависимостей от Arduino, поэтому его проверяют host-тесты.
 */
#pragma once

#include <stddef.h>
#include <stdint.h>

/*
 * Скопировать строку в буфер фиксированного размера:
 *   - ведущие и хвостовые пробелы/переводы строк отбрасываются;
 *   - копия обрезается так, чтобы не разорвать UTF-8 символ;
 *   - при встрече с некорректной последовательностью копирование прекращается;
 *   - результат всегда завершён нулём (dstSize > 0).
 */
void text_set(char* dst, size_t dstSize, const char* src);

/*
 * Экранировать строку для JSON: кавычки, обратный слэш, управляющие символы.
 * Байты >= 0x20 копируются как есть (UTF-8 проходит без изменений).
 * Результат всегда завершён нулём; при нехватке места строка обрезается.
 */
void text_json_escape(const char* in, char* out, size_t outSize);

/* Длина UTF-8 строки в символах (для подсчёта в интерфейсе/тестах). */
size_t text_utf8_len(const char* s);
