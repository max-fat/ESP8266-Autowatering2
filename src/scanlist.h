/*
 * scanlist.h - обработка результатов сканирования Wi-Fi.
 *
 * Модуль не знает про ESP8266: на вход приходит «сырой» список сетей от
 * WiFi.scanNetworks(), на выходе — аккуратный список для интерфейса:
 *   - скрытые сети (пустой SSID) выбрасываются;
 *   - дубликаты SSID склеиваются в одну запись (остаётся самый сильный сигнал);
 *   - записи сортируются по уровню сигнала (сильные первыми);
 *   - список обрезается до maxOut записей, но сильные сети не теряются.
 *
 * Логика чистая (без Arduino), поэтому её проверяют host-тесты.
 */
#pragma once

#include <stddef.h>
#include <stdint.h>

#define SCAN_SSID_MAX 32       /* длина SSID в байтах, без завершающего нуля */

struct ScanNet {
  char    ssid[SCAN_SSID_MAX + 1];   /* имя сети, всегда завершено нулём */
  int8_t  rssi;                      /* уровень сигнала, дБм (отрицательный) */
  uint8_t secured;                   /* 1 = нужен пароль, 0 = открытая сеть */
};

/*
 * Собрать итоговый список сетей.
 *   in      - сырые записи (ssid должен быть завершён нулём);
 *   count   - сколько записей во входном массиве;
 *   out     - куда писать результат (может совпадать с in);
 *   maxOut  - размер выходного массива.
 * Возвращает количество записей в out.
 */
uint8_t scanlist_build(const ScanNet* in, uint8_t count, ScanNet* out, uint8_t maxOut);
